 def xy(self,x,y):return 45+x*6.6,100+y*6.6
 def text(self,x,y,t,size=14,color='#25362f'):
  self.s.append(f'<text x="{x}" y="{y}" font-family="Segoe UI,Arial,sans-serif" font-size="{size}" fill="{color}">{escape(t)}</text>')
 def label(self,x,y,t):self.text(*self.xy(x,y),t,13)
 def rect(self,x,y,w,h,color,label=''):
  a,b=self.xy(x,y);self.s.append(f'<rect x="{a}" y="{b}" width="{w*6.6}" height="{h*6.6}" rx="5" fill="{color}" stroke="#667163"/>')
  if label:self.label(x+1,y+3,label)
 def oval(self,x,y,rx,ry,color,label=''):
  a,b=self.xy(x,y);self.s.append(f'<ellipse cx="{a}" cy="{b}" rx="{rx*6.6}" ry="{ry*6.6}" fill="{color}" stroke="#667163" stroke-width="2"/>')
  if label:self.label(x-rx+1,y,label)
 def line(self,pts,color='#b6a381',width=15,arrow=False,cam=False):
  ps=' '.join(f'{a},{b}' for a,b in [self.xy(*p) for p in pts]);mark=' marker-end="url(#cam)"' if cam else (' marker-end="url(#arrow)"' if arrow else '')
  self.s.append(f'<polyline points="{ps}" fill="none" stroke="{color}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"{mark}/>')
 def camera(self,id,x,y,tx,ty):
  self.line([(x,y),(tx,ty)],'#8b4d92',2,cam=True);a,b=self.xy(x,y);self.s.append(f'<circle cx="{a}" cy="{b}" r="12" fill="#8b4d92"/>');self.text(a+15,b-8,id,13,'#713a78')
 def note(self,n,t):self.text(735,330+n*25,t,13)
 def save(self,name):
  self.text(45,800,'Camera arrows show aim only; framing and lens are specified in the companion plan.',14)
  (P/name).write_text('\n'.join(self.s)+ '</svg>',encoding='utf-8')
